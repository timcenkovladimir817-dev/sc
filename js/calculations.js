function fmtNum(v,digits=2){
  const n=Number(v);
  if(!Number.isFinite(n))return '—';
  return n.toLocaleString('ru-RU',{maximumFractionDigits:digits});
}

function pnToKgf(pnMpa){return Number(pnMpa)*10;}

function nearestFlangePn(pnMpa){
  const p=Number(pnMpa);
  if(!Number.isFinite(p))return null;
  for(const candidate of PN_SERIES_33259){
    if(candidate>=p-1e-9)return candidate;
  }
  return null;
}

function allowablePressureAt(groupKey,pnMpa,temperature){
  const group=STEEL_GROUPS[groupKey];
  if(!group)return null;
  const t=Number(temperature);
  const pn=Number(pnMpa);
  if(!Number.isFinite(t)||!Number.isFinite(pn))return null;
  if(t<group.minTemp||t>group.maxTemp)return null;
  const row=group.rows.find(r=>Math.abs(r.pn-pn)<1e-9);
  if(!row)return null;
  if(t<=20)return row.pn; // PN по определению — при 20 °C
  const points=[{t:20,p:row.pn}];
  group.temps.forEach((temp,i)=>{
    const value=row.values[i];
    if(value!==null&&value!==undefined&&Number.isFinite(value))points.push({t:temp,p:value});
  });
  const last=points[points.length-1];
  if(!last||t>last.t)return null;
  for(let i=1;i<points.length;i++){
    const a=points[i-1],b=points[i];
    if(t<=b.t){
      if(b.t===a.t)return b.p;
      return a.p+(b.p-a.p)*(t-a.t)/(b.t-a.t);
    }
  }
  return null;
}

function requiredPnFor(groupKey,pressureMpa,temperature){
  const group=STEEL_GROUPS[groupKey];
  if(!group)return {error:'Неизвестная группа материала.'};
  const pressure=Number(pressureMpa);
  const t=Number(temperature);
  if(!Number.isFinite(pressure)||pressure<=0)return {error:'Рабочее давление должно быть положительным числом.'};
  if(!Number.isFinite(t))return {error:'Температура должна быть числом.'};
  if(t<group.minTemp)return {error:`Для выбранного материала таблица не распространяется на температуры ниже ${fmtNum(group.minTemp,0)} °C.`};
  if(t>group.maxTemp)return {error:`Для выбранного материала нет табличных данных выше ${fmtNum(group.maxTemp,0)} °C.`};
  const candidates=[];
  for(const row of group.rows){
    const allow=allowablePressureAt(groupKey,row.pn,t);
    if(allow===null)continue;
    candidates.push({pn:row.pn,allow,test:row.test});
  }
  const chosen=candidates.find(c=>pressure<=c.allow*1.05+1e-9);
  if(!chosen)return {error:`Рабочее давление ${fmtNum(pressure)} МПа при ${fmtNum(t,0)} °C превышает табличный диапазон для выбранного материала.`};
  return {
    groupKey,group,pressure,temperature:t,
    pn:chosen.pn,allow:chosen.allow,test:chosen.test,
    pnKgf:pnToKgf(chosen.pn),
    flangePn:nearestFlangePn(chosen.pn),
    usedTolerance:pressure>chosen.allow+1e-9,
    margin:chosen.allow*1.05-pressure
  };
}

function calcPnAtTemperature(groupKey,pnMpa,temperature){
  const group=STEEL_GROUPS[groupKey];
  if(!group)return {error:'Неизвестная группа материала.'};
  const t=Number(temperature);
  const pn=Number(pnMpa);
  if(!Number.isFinite(t))return {error:'Температура должна быть числом.'};
  if(!Number.isFinite(pn))return {error:'Не выбрано номинальное давление PN.'};
  if(t<group.minTemp||t>group.maxTemp)return {error:`Диапазон таблицы для выбранного материала: ${fmtNum(group.minTemp,0)}…${fmtNum(group.maxTemp,0)} °C.`};
  const row=group.rows.find(r=>Math.abs(r.pn-pn)<1e-9);
  if(!row)return {error:'Для выбранного материала нет такой ступени PN.'};
  const allow=allowablePressureAt(groupKey,pn,t);
  if(allow===null)return {error:`При PN ${fmtNum(pn)} МПа и температуре ${fmtNum(t,0)} °C таблица не допускает применение (прочерк).`};
  return {group,groupKey,pn,test:row.test,temperature:t,allow,pnKgf:pnToKgf(pn)};
}

